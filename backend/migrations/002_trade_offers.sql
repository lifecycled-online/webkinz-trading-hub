CREATE TABLE public.trade_offers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuer text NOT NULL,
    sender_subject text NOT NULL,
    recipient_subject text NOT NULL,
    message text NOT NULL DEFAULT '' CHECK (char_length(message) <= 500),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'declined', 'withdrawn')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (sender_subject <> recipient_subject)
);

CREATE INDEX trade_offers_recipient_status_created_idx
    ON public.trade_offers (issuer, recipient_subject, status, created_at DESC);

CREATE INDEX trade_offers_sender_created_idx
    ON public.trade_offers (issuer, sender_subject, created_at DESC);

CREATE TABLE public.trade_offer_items (
    offer_id bigint NOT NULL REFERENCES public.trade_offers (id) ON DELETE CASCADE,
    side text NOT NULL CHECK (side IN ('offering', 'requesting')),
    item_id text NOT NULL CHECK (char_length(item_id) BETWEEN 1 AND 200),
    PRIMARY KEY (offer_id, side, item_id)
);